"""metadata/bulk split — the bulk side (DESIGN §3.4).

A data item = lightweight **metadata** that travels on the control flow + **bulk**
(video/image/large tensors) that STAYS where produced and is pulled on demand. This
module is the bulk side: a `BulkStore` (lives with the producer) hands out `BulkRef`
handles; the bulk is fetched only when a consumer actually needs it.

Payoff (DESIGN §3.4): control flow / routing / dispatch / filtering touch only
metadata (BulkRefs) — dropped samples' bulk never moves (filter-before-transfer).

v0: single-process, in-memory store + a module registry so a ref finds its store.
TODO(v1+): remote addressing (rkey / IPC handle / endpoint) on the ref; refcount/
lease + timeout GC; HBM→host→NVMe spill; the cross-process pull goes through
transport + the connection registry.
"""

from __future__ import annotations

import itertools
import threading
from collections.abc import Iterable

from cosmos_framework.posttrain.comm.transfer.mover import BulkRef

_STORE_REGISTRY: dict[str, "BulkStore"] = {}
_store_ids = itertools.count()


class BulkStore:
    """Producer-side residence for bulk. v0: in-memory dict.

    Thread safety (deadlock fix 2026-07-22): the store is NO LONGER single-threaded. The
    hosting `_Host` Ray actor now serves the bulk-plane pull methods (`fetch_bulk*`,
    `release_bulk`) from a dedicated "bulk" concurrency group so a peer can pull this
    producer's bulk WHILE the producer's own body is blocked in a collective (see
    workers/ray.py — this is what closes the collective-blocked-peer deadlock). That means a
    fetch on the bulk thread can race a `put`/`pack_payload` on the invoke thread, so `put`,
    `fetch`, `release`, and `__len__` (fetch_count increment included) are guarded by
    `self._lock`. The lock is uncontended on the common path and held only around the dict
    mutations, never across a transport/RPC. State that is touched ONLY from the actor's
    `_default` (invoke) thread — the `_pending_releases` release sweep — stays single-threaded
    and does not go through this lock."""

    def __init__(self, store_id: str | None = None):
        """Create an in-memory bulk store and register it so refs can locate it.

        Args:
            store_id: Explicit registry id; defaults to an autogenerated ``store{N}``.
        """
        self.id = store_id or f"store{next(_store_ids)}"
        self._data: dict[int, object] = {}
        self._readers: dict[int, int] = {}
        # The reader count a key's refcount was FIRST initialized with — the consistency baseline for
        # the silent-leak guard below (a later fetch/release passing a different non-default readers
        # for the same live key is a routing-map disagreement). Popped when the key is fully drained.
        self._init_readers: dict[int, int] = {}
        self._keys = itertools.count()
        self.fetch_count = 0  # instrumentation: proves filter-before-transfer
        self._lock = threading.Lock()  # serializes store mutations across invoke + bulk threads
        _STORE_REGISTRY[self.id] = self

    def put(self, obj: object, nbytes: int = 0, dtype: str = "") -> BulkRef:
        """Store `obj` under a fresh key and return a `BulkRef` handle to it.

        Args:
            obj: The bulk object to retain in this producer's store.
            nbytes: Byte size recorded on the ref (instrumentation / tiering metadata).
            dtype: Dtype string recorded on the ref.

        Returns:
            A `BulkRef` addressing this store's id and the newly assigned key.
        """
        with self._lock:
            k = next(self._keys)
            self._data[k] = obj
        return BulkRef.for_bulk(self.id, k, nbytes, dtype)

    def _track_readers(self, key: int, readers: int) -> None:
        """Validate and record a key's initial reader count (silent-leak guard).

        Args:
            key: Bulk key whose refcount baseline is being checked / initialized.
            readers: Expected reader count for this call; must be >= 1, and must match the
                key's initialized baseline when non-default.
        """
        # Refcount-consistency guard (silent-leak trap): ``readers`` must be >= 1, and once a key's
        # counter is initialized with a reader count, a LATER fetch/release passing a DIFFERENT
        # NON-DEFAULT ``readers`` for the same LIVE key is a wiring bug — the routing map disagrees
        # with itself, so the refcount would never reach 0 and the bulk leaks. ``readers`` omitted /
        # default (== 1) stays compatible (the common single-reader path never trips this). Called
        # under ``self._lock`` from the counter-affecting paths (consume fetch + release).
        if readers < 1:
            raise ValueError(f"readers must be >= 1, got {readers} (bulk key {key})")
        prior = self._init_readers.get(key)
        if prior is None:
            self._init_readers[key] = readers
        elif readers != 1 and readers != prior:
            raise ValueError(
                f"inconsistent reader count for bulk key {key}: refcount was initialized with "
                f"readers={prior} but a later call passed readers={readers} — the routing map "
                f"disagrees with itself (the refcount would never reach 0, leaking the bulk)"
            )

    def fetch(self, ref: BulkRef, consume: bool = True, readers: int = 1) -> object:
        """Return the bulk for `ref`, decrementing its refcount unless `consume` is False.

        Args:
            ref: Handle identifying the bulk key to read.
            consume: If True, decrement the reader count and pop at zero; if False, peek without consuming.
            readers: Total consumer count used to initialize the refcount on the first consuming fetch.

        Returns:
            The stored bulk object.
        """
        # Refcounted consume (design spec 2026-07-22 §2.4): the routing map knows how many
        # consumer cells will materialize this ref; first fetch initializes the counter,
        # each consuming fetch decrements, pop at zero. readers=1 == the old consume-once.
        # Lock-guarded: this runs on the actor's "bulk" thread and may race a put/pack on the
        # invoke thread (see the class docstring — the store is no longer single-threaded).
        with self._lock:
            self.fetch_count += 1
            if not consume:
                return self._data[ref.key]
            self._track_readers(ref.key, readers)
            left = self._readers.get(ref.key, readers) - 1
            if left <= 0:
                self._readers.pop(ref.key, None)
                self._init_readers.pop(ref.key, None)
                return self._data.pop(ref.key)
            self._readers[ref.key] = left
            return self._data[ref.key]

    def release(self, ref: BulkRef, readers: int = 1) -> None:
        """Decrement `ref`'s reader count on the drop path without transferring data.

        Args:
            ref: Handle identifying the bulk key to release.
            readers: Total consumer count used to lazily initialize the refcount if unset.
        """
        # Drop-path bookkeeping: decrement reader count WITHOUT transferring data or
        # counting toward fetch_count (which means "data pulled"). Lazily initializes
        # counter so release() works before any fetch() (e.g., on_metadata split that
        # drops a ref without materializing it). Fails loud (KeyError) on double-release
        # or release of never-put refs — consistent with this codebase's posture.
        # Lock-guarded (bulk-thread `release_bulk` vs. invoke-thread put/pack).
        with self._lock:
            if ref.key not in self._data:
                raise KeyError(ref.key)
            self._track_readers(ref.key, readers)
            left = self._readers.get(ref.key, readers) - 1
            if left <= 0:
                self._readers.pop(ref.key, None)
                self._init_readers.pop(ref.key, None)
                self._data.pop(ref.key)
            else:
                self._readers[ref.key] = left

    def discard_unconsumed(self, refs: Iterable[BulkRef]) -> None:
        """Retire exclusively owned staging after a failed or abandoned peer call.

        A peer has one reader and may already have consumed these entries. Callers must pass
        only refs they created for that call, never previously published or shared refs.
        Successful calls may transfer ownership to a metadata-only peer and must not discard it.
        """
        with self._lock:
            for ref in refs:
                self._data.pop(ref.key, None)
                self._readers.pop(ref.key, None)
                self._init_readers.pop(ref.key, None)

    def __len__(self) -> int:
        """Return the number of live (un-consumed) bulk entries.

        Returns:
            Count of bulk objects still resident in the store.
        """
        with self._lock:
            return len(self._data)  # live (un-consumed) bulk entries


def store_for(ref: BulkRef) -> BulkStore:
    # v0: same-process registry. TODO(v1+): locate via connection registry + transport.
    return _STORE_REGISTRY[ref.store_id]


def has_local_store(ref: BulkRef) -> bool:
    """True if the ref's bulk lives in THIS process (⇒ zero-copy direct pull). False ⇒
    the producer is remote; the transport must pull one-sided via the connection
    registry (DESIGN §3.4 remote addressing / §3.2 registry)."""
    return ref.store_id in _STORE_REGISTRY
